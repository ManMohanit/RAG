"""Day 3: a free, local-retrieval + Gemini-generation RAG + agentic AI MVP.

Run: .\\.venv\\Scripts\\streamlit.exe run app.py

Retrieval (TF-IDF) stays fully local and free, as before. The final
answer is now generated by the free Gemini API from the retrieved
evidence, which gives a real synthesized answer instead of just raw
chunk text. If no GEMINI_API_KEY is set, the app automatically falls
back to the old local-only "dump the evidence" answer, so it still
runs with zero configuration.

Set GEMINI_API_KEY in .streamlit/secrets.toml (or as an environment
variable) to enable generation. Get a free key at
https://aistudio.google.com/apikey

Install with:
pip install pypdf scikit-learn google-genai
"""

import os
from dataclasses import dataclass

import streamlit as st
from pypdf import PdfReader
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity
from google import genai


MODEL_NAME = "gemini-2.5-flash"


@dataclass
class Chunk:
    text: str
    source: str
    page: int


def chunk_text(text: str, source: str, page: int, size: int = 700, overlap: int = 120):
    """Split text into overlapping word chunks, retaining traceable metadata."""
    words = text.split()
    chunks = []
    step = size - overlap
    for start in range(0, len(words), step):
        part = " ".join(words[start : start + size]).strip()
        if part:
            chunks.append(Chunk(part, source, page))
    return chunks


def read_uploads(uploaded_files):
    chunks = []
    for file in uploaded_files:
        if file.name.lower().endswith(".pdf"):
            reader = PdfReader(file)
            for page_no, page in enumerate(reader.pages, 1):
                chunks.extend(chunk_text(page.extract_text() or "", file.name, page_no))
        else:
            text = file.getvalue().decode("utf-8", errors="ignore")
            chunks.extend(chunk_text(text, file.name, 1))
    return chunks


def choose_tool(question: str) -> str:
    """The intentionally simple agent policy: decide which available tool fits."""
    q = question.lower()
    if any(word in q for word in ("summarize", "summary", "overview", "gist")):
        return "summarize_document"
    if any(word in q for word in ("according to", "document", "pdf", "uploaded", "source")):
        return "search_documents"
    return "search_documents"  # Prefer grounded answers whenever documents are present.


def retrieve(question: str, chunks: list[Chunk], top_k: int = 3):
    corpus = [c.text for c in chunks]
    vectorizer = TfidfVectorizer(stop_words="english")
    matrix = vectorizer.fit_transform(corpus + [question])
    scores = cosine_similarity(matrix[-1], matrix[:-1]).flatten()
    best = scores.argsort()[::-1][:top_k]
    return [(chunks[i], float(scores[i])) for i in best if scores[i] > 0]


def get_api_key():
    """Read API key from Streamlit secrets or environment variable."""
    try:
        return st.secrets["GEMINI_API_KEY"]
    except (KeyError, FileNotFoundError):
        return os.getenv("GEMINI_API_KEY")


def local_answer(question: str, results):
    """Fallback: a transparent answer built purely from retrieved evidence, no API needed."""
    if not results:
        return "I couldn't find an answer in the uploaded documents. Try a more specific question."
    evidence = "\n\n".join(item.text for item, _ in results)
    return (
        "**Local RAG answer** *(no Gemini API key set — showing raw evidence)*\n\n"
        f"The most relevant information for *{question}* is:\n\n{evidence[:1600]}"
    )


def gemini_answer(question: str, results):
    """Generate a real synthesized answer from Gemini, grounded in retrieved evidence."""
    if not results:
        return "I couldn't find an answer in the uploaded documents. Try a more specific question."

    api_key = get_api_key()
    if not api_key:
        return local_answer(question, results)

    evidence = "\n\n".join(
        f"[{i}] (source: {chunk.source}, page {chunk.page})\n{chunk.text}"
        for i, (chunk, _score) in enumerate(results, 1)
    )
    prompt = (
        "Answer the question using ONLY the evidence excerpts below. "
        "Cite sources inline like [1], [2]. If the evidence doesn't "
        "contain the answer, say so plainly instead of guessing.\n\n"
        f"Question: {question}\n\nEvidence:\n{evidence[:6000]}"
    )

    try:
        client = genai.Client(api_key=api_key)
        response = client.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
        )
        return f"**Gemini RAG answer**\n\n{response.text}"
    except Exception as error:  # noqa: BLE001 - surface a friendly fallback
        st.warning(f"Gemini request failed ({error}); showing local evidence instead.")
        return local_answer(question, results)


st.set_page_config(page_title="SelfAI RAG", page_icon="📚", layout="wide")
st.title("📚 SelfAI Document Assistant")
st.caption("Day 3: local TF-IDF retrieval + free Gemini generation, with explainable agent decisions and source citations.")

with st.sidebar:
    st.header("1. Upload knowledge")
    files = st.file_uploader("PDF or text files", type=["pdf", "txt", "md"], accept_multiple_files=True)
    st.markdown("**Agent tools**\n- Search documents\n- Summarize document\n- Return Gemini-generated, evidence-grounded answer")
    if not get_api_key():
        st.info("No `GEMINI_API_KEY` set — running in local-only fallback mode. Get a free key at aistudio.google.com/apikey.")

if files:
    chunks = read_uploads(files)
    st.success(f"Indexed {len(chunks)} text chunks from {len(files)} file(s).")
    question = st.text_input("2. Ask a question", placeholder="What are the main eligibility requirements?")
    if question:
        tool = choose_tool(question)
        st.info(f"Agent decision: `{tool}`")
        results = retrieve(question, chunks)
        st.subheader("Answer")
        with st.spinner("Generating answer..."):
            st.markdown(gemini_answer(question, results))
        with st.expander("View retrieved evidence and citations"):
            if results:
                for i, (chunk, score) in enumerate(results, 1):
                    st.markdown(f"**{i}. {chunk.source}, page {chunk.page}** — relevance: {score:.2f}")
                    st.write(chunk.text[:600] + ("…" if len(chunk.text) > 600 else ""))
            else:
                st.write("No relevant document chunks found.")
else:
    st.info("Upload one or more PDF, TXT, or Markdown files to begin.")
    st.markdown("""
    ### How the MVP works
    1. It splits your files into overlapping chunks.
    2. TF-IDF retrieves the most relevant chunks (the RAG retrieval step) — fully local and free.
    3. A small agent policy chooses the retrieval tool.
    4. The free Gemini API synthesizes a grounded, cited answer from the retrieved text
       (falls back to showing raw evidence if no API key is configured).
    """)